def cmd_ledger(proj, ledger_path, strict):
    data = json.loads(Path(ledger_path).read_text(encoding="utf-8"))
    claims = data["claims"] if isinstance(data, dict) else data
    rep, seen = Report(), set()
    tally = {"module": 0, "decision": 0, "dropped": 0, "unaccounted": 0}
    for c in claims:
        cid, text = c.get("id", "?"), c.get("text", "")
        where = f"{cid} ({c.get('source', 'no source')})"
        if cid in seen:
            rep.err("ledger-id", where, "duplicate claim id")
        seen.add(cid)
        if not text.strip():
            rep.err("ledger-text", where, "empty claim text")
            continue
        disp, target = c.get("disposition"), c.get("target", "")
        reworded = bool(c.get("reworded"))
        flag = rep.warn if reworded else rep.err
        if disp == "module":
            mod, slug, e = proj.resolve(target)
            if e:
                rep.err("ledger-target", where, e)
                tally["unaccounted"] += 1
                continue
            hay = norm("\n".join(proj.modules[mod].subtree(slug, clean=False)))
            if norm(text) not in hay:
                flag("not-verbatim", where, f"claim text not found verbatim in {target}" +
                     (" (marked reworded)" if reworded else "; move text verbatim or set reworded:true with user approval"))
                tally["module" if reworded else "unaccounted"] += 1
            else:
                tally["module"] += 1
        elif disp == "decision":
            d = proj.decisions.get(target)
            if d is None:
                rep.err("ledger-target", where, f"unknown decision '{target}'")
                tally["unaccounted"] += 1
                continue
            if norm(text) not in norm(d["raw"] + " " + d["title"]):
                flag("not-verbatim", where, f"claim text not found verbatim in {target}")
                tally["decision" if reworded else "unaccounted"] += 1
            else:
                tally["decision"] += 1
        elif disp == "dropped":
            if not c.get("reason") or c.get("approved") is not True:
                rep.err("ledger-dropped", where, "dropped claims need a 'reason' and 'approved': true (user sign-off)")
                tally["unaccounted"] += 1
            else:
                tally["dropped"] += 1
        else:
            rep.err("ledger-unaccounted", where, f"no valid disposition ({disp!r}); text: {text[:70]}")
            tally["unaccounted"] += 1
    rep.print()
    print(f"\n{len(claims)} claims: {tally['module']} in modules, {tally['decision']} in decision log, "
          f"{tally['dropped']} dropped with approval, {tally['unaccounted']} unaccounted")
    e, w = rep.count("ERROR"), rep.count("WARN")
    return 1 if e or (strict and w) else 0


