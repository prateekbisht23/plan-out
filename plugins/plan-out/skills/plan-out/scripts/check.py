#!/usr/bin/env python3
"""plan-out checker: mechanical consistency checks for a modular docs folder.

Standard library only (Python 3.8+). Run from anywhere:

  check.py [check] [--docs DIR] [--strict]    run every consistency check
  check.py impact REF [--docs DIR]            what depends on module#section?
  check.py archive FEATURE [--docs DIR]       finish a feature: archive its tasks
  check.py index [--docs DIR] [--force]       regenerate docs/README.md
  check.py ledger LEDGER.json [--docs DIR]    verify a cleanup claim ledger

Expected layout (DIR defaults to ./docs):
  modules/<name>.md     spec modules (frontmatter + ## sections)
  decisions.md          decision log (## D-001: Title + "- key: value" lines)
  tasks/<feature>.md    active task lists (tasks/archive/ is ignored)

Exit code is 1 when any ERROR is found (or any WARN with --strict).
"""
import argparse
import datetime
import json
import re
import sys
from pathlib import Path

MODULE_STATUSES = ("planned", "in-progress", "implemented")
DECISION_STATUSES = ("active", "superseded")
# Sections that describe rather than specify; they need no implementing task.
META_SLUGS = {
    "overview", "purpose", "summary", "scope", "non-goals", "glossary",
    "terms", "open-questions", "related-modules", "change-notes",
}
GENERATED_MARK = "<!-- generated by plan-out"

FENCE = re.compile(r"^\s*(```|~~~)")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)(?:\s+#+)?\s*$")
LINK = re.compile(r"(?<!!)\[([^\]]*)\]\(([^)\s]+)\)")
DREF = re.compile(r"\[(D-\d+)\]")
DHEAD = re.compile(r"^(D-\d+)\s*[:\-\u2013\u2014]?\s*(.*)$")
DFIELD = re.compile(r"^\s*[-*]\s+([A-Za-z_][A-Za-z_ ]*?):\s*(.*)$")
TASK = re.compile(r"^\s*[-*]\s+\[([ xX])\]\s+(T-\d+)\s*[:\-\u2013\u2014]?\s*(.*)$")
TASK_IMPL = re.compile(r"^\s+(?:[-*]\s+)?implements:\s*(.+)$", re.I)
TASK_REVIEW = re.compile(r"^\s+(?:[-*]\s+)?review:\s*(.+)$", re.I)
TERM = re.compile(r"^\s*[-*]\s+\*\*(.+?)\*\*\s*[:\-\u2013\u2014]")
PLACEHOLDER = re.compile(r"\b(TBD|TODO|FIXME)\b|\?\?\?")
OPEN_Q = re.compile(r"^\s*[-*]\s+\[ \]")
NO_TASK = "<!-- no-task -->"


# --------------------------------------------------------------------------
# Markdown helpers
# --------------------------------------------------------------------------
def slugify(title):
    """GitHub-style heading anchor."""
    t = re.sub(r"[^\w\- ]", "", title.strip().lower())
    return t.replace(" ", "-")


def split_frontmatter(lines):
    """Return (meta dict, index of first body line)."""
    if lines and lines[0].strip() == "---":
        for i in range(1, len(lines)):
            if lines[i].strip() == "---":
                meta = {}
                for line in lines[1:i]:
                    m = re.match(r"^([A-Za-z_][\w-]*)\s*:\s*(.*)$", line)
                    if m:
                        meta[m.group(1).lower()] = m.group(2).strip().strip("\"'")
                return meta, i + 1
    return {}, 0


def fenced_flags(lines):
    """True for every line that is inside (or is the edge of) a code fence."""
    flags, inside, tok = [], False, None
    for line in lines:
        m = FENCE.match(line)
        if m:
            if not inside:
                inside, tok = True, m.group(1)
            elif m.group(1) == tok:
                inside = False
            flags.append(True)
            continue
        flags.append(inside)
    return flags


def norm(text):
    """Normalise text for verbatim comparison: drop list markers, collapse space."""
    out = []
    for line in text.splitlines():
        line = line.strip()
        line = re.sub(r"^(?:[-*+]|\d+\.)\s+", "", line)
        line = re.sub(r"^>\s?", "", line)
        out.append(line)
    return re.sub(r"\s+", " ", " ".join(out)).strip()


class Doc:
    def __init__(self, path, root):
        self.path = path
        try:
            self.rel = path.relative_to(root).as_posix()
        except ValueError:
            self.rel = path.name
        self.lines = path.read_text(encoding="utf-8").splitlines()
        self.meta, self.body_start = split_frontmatter(self.lines)
        flags = fenced_flags(self.lines)
        self.clean = ["" if f else ln for ln, f in zip(self.lines, flags)]
        self.secs = []
        for i in range(self.body_start, len(self.lines)):
            if flags[i]:
                continue
            m = HEADING.match(self.lines[i])
            if m:
                self.secs.append({"level": len(m.group(1)), "title": m.group(2),
                                  "slug": slugify(m.group(2)), "line": i})

    def anchors(self):
        return {s["slug"] for s in self.secs}

    def index_of(self, slug):
        for i, s in enumerate(self.secs):
            if s["slug"] == slug:
                return i
        return None

    def end_of(self, i):
        level = self.secs[i]["level"]
        for j in range(i + 1, len(self.secs)):
            if self.secs[j]["level"] <= level:
                return self.secs[j]["line"]
        return len(self.lines)

    def subtree(self, slug, clean=True):
        """Lines of a section including its sub-sections (None slug = whole body)."""
        src = self.clean if clean else self.lines
        if slug is None:
            return src[self.body_start:]
        i = self.index_of(slug)
        if i is None:
            return []
        return src[self.secs[i]["line"] + 1:self.end_of(i)]

    def subtree_slugs(self, slug):
        if slug is None:
            return self.anchors()
        i = self.index_of(slug)
        if i is None:
            return set()
        end = self.end_of(i)
        return {s["slug"] for s in self.secs[i:] if s["line"] < end}


def parse_decisions(doc):
    """Return ({id: entry}, [(id, message)]) from decisions.md."""
    decisions, problems = {}, []
    for i, s in enumerate(doc.secs):
        if s["level"] != 2:
            continue
        m = DHEAD.match(s["title"])
        if not m:
            continue
        did, title = m.group(1), m.group(2)
        if did in decisions:
            problems.append((did, "duplicate decision id"))
        body = doc.lines[s["line"] + 1:doc.end_of(i)]
        fields, key = {}, None
        for line in body:
            fm = DFIELD.match(line)
            if fm:
                key = fm.group(1).strip().lower().replace(" ", "_")
                fields[key] = fm.group(2).strip()
            elif key and line.strip() and line.startswith((" ", "\t")):
                fields[key] += " " + line.strip()
        decisions[did] = {"title": title, "fields": fields,
                          "raw": "\n".join(body), "line": s["line"] + 1}
    return decisions, problems


def parse_tasks(doc):
    tasks, cur = [], None
    for i, line in enumerate(doc.clean):
        m = TASK.match(line)
        if m:
            cur = {"id": m.group(2), "done": m.group(1) in "xX", "title": m.group(3),
                   "line": i + 1, "implements": [], "review": None}
            tasks.append(cur)
            continue
        if cur is None or not line.strip():
            continue
        if not line.startswith((" ", "\t")):
            cur = None
            continue
        mi = TASK_IMPL.match(line)
        if mi:
            cur["implements"] += [r.strip().strip("`") for r in mi.group(1).split(",") if r.strip()]
            continue
        mr = TASK_REVIEW.match(line)
        if mr:
            cur["review"] = mr.group(1).strip()
    return tasks


class Report:
    def __init__(self):
        self.items = []

    def err(self, rule, where, msg):
        self.items.append(("ERROR", rule, where, msg))

    def warn(self, rule, where, msg):
        self.items.append(("WARN", rule, where, msg))

    def count(self, level):
        return sum(1 for i in self.items if i[0] == level)

    def print(self):
        for level, rule, where, msg in self.items:
            print(f"{level:5} [{rule}] {where}: {msg}")


