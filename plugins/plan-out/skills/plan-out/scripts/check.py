class Project:
    def __init__(self, docs):
        self.root = Path(docs).resolve()
        self.modules, self.task_docs, self.tasks = {}, {}, {}
        self.decisions, self.decision_problems, self.dec_doc = {}, [], None
        self._anchor_cache = {}
        mod_dir = self.root / "modules"
        if mod_dir.is_dir():
            for p in sorted(mod_dir.glob("*.md")):
                if p.name.lower() not in ("readme.md", "index.md"):
                    self.modules[p.stem] = Doc(p, self.root)
        dec = self.root / "decisions.md"
        if dec.is_file():
            self.dec_doc = Doc(dec, self.root)
            self.decisions, self.decision_problems = parse_decisions(self.dec_doc)
        task_dir = self.root / "tasks"
        if task_dir.is_dir():
            for p in sorted(task_dir.glob("*.md")):
                d = Doc(p, self.root)
                self.task_docs[p.stem] = d
                self.tasks[p.stem] = parse_tasks(d)

    def all_docs(self):
        docs = list(self.modules.values()) + list(self.task_docs.values())
        return docs + ([self.dec_doc] if self.dec_doc else [])

    def anchors_of(self, path):
        path = path.resolve()
        if path not in self._anchor_cache:
            self._anchor_cache[path] = Doc(path, self.root).anchors()
        return self._anchor_cache[path]

    def resolve(self, ref):
        """'module#slug' -> (module, slug|None, error|None)."""
        ref = ref.strip().strip("`")
        mod, _, slug = ref.partition("#")
        mod = re.sub(r"\.md$", "", mod.split("/")[-1])
        if mod not in self.modules:
            return mod, slug or None, f"unknown module '{mod}'"
        if slug and slug not in self.modules[mod].anchors():
            return mod, slug, f"module '{mod}' has no section '#{slug}'"
        return mod, slug or None, None

    def active_task_refs(self):
        """[(file, task, module, slug)] for every implements: ref that resolves."""
        out = []
        for fname, tasks in self.tasks.items():
            for t in tasks:
                for ref in t["implements"]:
                    mod, slug, e = self.resolve(ref)
                    if not e:
                        out.append((fname, t, mod, slug))
        return out


