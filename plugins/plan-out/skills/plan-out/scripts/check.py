def set_module_status(path, new):
    lines = path.read_text(encoding="utf-8").splitlines()
    _, start = split_frontmatter(lines)
    for i in range(1, max(start - 1, 1)):
        if re.match(r"^status\s*:", lines[i]):
            lines[i] = f"status: {new}"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def cmd_archive(proj, feature, date, strict):
    tasks = proj.tasks.get(feature)
    if tasks is None:
        print(f"ERROR: tasks/{feature}.md not found")
        return 1
    open_tasks = [t for t in tasks if not t["done"]]
    if open_tasks or not tasks:
        print(f"Cannot archive: {len(open_tasks)} task(s) still open (or file has no tasks):")
        for t in open_tasks:
            print(f"  {t['id']} {t['title']}")
        return 1
    touched = {m for t in tasks for m, _, e in (proj.resolve(r) for r in t["implements"]) if not e}
    src = proj.task_docs[feature].path
    dest_dir = src.parent / "archive"
    dest_dir.mkdir(exist_ok=True)
    dest = dest_dir / f"{feature}-{date}.md"
    if dest.exists():
        print(f"ERROR: {dest} already exists")
        return 1
    src.rename(dest)
    fresh = Project(proj.root)
    flipped = []
    for mod in sorted(touched):
        still_open = [1 for _, t, m, _ in fresh.active_task_refs() if m == mod and not t["done"]]
        if not still_open and fresh.modules[mod].meta.get("status") != "implemented":
            set_module_status(fresh.modules[mod].path, "implemented")
            flipped.append(mod)
    print(f"Archived to {dest.relative_to(proj.root).as_posix()}")
    print("Marked implemented: " + (", ".join(flipped) or "(none; other tasks still open)"))
    final = Project(proj.root)
    cmd_index(final, force=False, quiet=True)
    print("\nFinal check:")
    return cmd_check(final, strict)


def cmd_index(proj, force, quiet=False):
    target = proj.root / "README.md"
    if target.exists() and GENERATED_MARK not in target.read_text(encoding="utf-8") and not force:
        print(f"ERROR: {target} exists and was not generated by plan-out; use --force to replace it")
        return 1
    n_active = sum(1 for d in proj.decisions.values() if d["fields"].get("status") == "active")
    n_sup = len(proj.decisions) - n_active
    out = [f"{GENERATED_MARK} (scripts/check.py index). Do not edit by hand. -->",
           "# Documentation index", "", "## Modules", "",
           "| Module | Status | Summary |", "| --- | --- | --- |"]
    for name, doc in proj.modules.items():
        out.append(f"| [{name}](modules/{name}.md) | {doc.meta.get('status', '?')} | {doc.meta.get('summary', '')} |")
    out += ["", "## Decisions", "",
            f"{n_active} active, {n_sup} superseded. See [decisions.md](decisions.md)."]
    if proj.tasks:
        out += ["", "## Work in progress", ""]
        for fname, tasks in proj.tasks.items():
            done = sum(1 for t in tasks if t["done"])
            out.append(f"- [tasks/{fname}.md](tasks/{fname}.md): {done} of {len(tasks)} tasks done")
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    if not quiet:
        print(f"Wrote {target}")
    return 0


