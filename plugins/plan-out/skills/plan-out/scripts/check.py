def run_checks(proj):
    rep = Report()
    if not proj.modules and not proj.tasks:
        rep.err("layout", str(proj.root), "no modules/ or tasks/ found; nothing to check")
        return rep
    if proj.dec_doc is None:
        rep.err("layout", "decisions.md", "decision log is missing")

    for did, msg in proj.decision_problems:
        rep.err("decision-id", f"decisions.md {did}", msg)

    # --- modules -----------------------------------------------------------
    term_owner = {}
    for name, doc in proj.modules.items():
        meta = doc.meta
        if not meta:
            rep.err("frontmatter", doc.rel, "missing frontmatter (module, status, summary)")
        else:
            if meta.get("module") != name:
                rep.err("frontmatter", doc.rel, f"'module:' is '{meta.get('module')}', expected '{name}'")
            if meta.get("status") not in MODULE_STATUSES:
                rep.err("frontmatter", doc.rel, f"status '{meta.get('status')}' not one of {MODULE_STATUSES}")
            if not meta.get("summary"):
                rep.warn("frontmatter", doc.rel, "missing one-line summary")
        seen = {}
        for s in doc.secs:
            if s["slug"] in seen:
                rep.err("duplicate-heading", f"{doc.rel}:{s['line'] + 1}",
                        f"heading '{s['title']}' duplicates line {seen[s['slug']] + 1}; anchors would collide")
            seen.setdefault(s["slug"], s["line"])
        for slug in ("glossary", "terms"):
            for line in doc.subtree(slug):
                m = TERM.match(line)
                if m:
                    term = m.group(1).strip().lower()
                    if term in term_owner and term_owner[term] != name:
                        rep.err("term-defined-twice", doc.rel,
                                f"term '{m.group(1)}' is also defined in module '{term_owner[term]}'; keep one definition and link to it")
                    term_owner.setdefault(term, name)
        for line in doc.subtree("open-questions"):
            if OPEN_Q.match(line):
                rep.warn("open-question", doc.rel, f"unresolved: {line.strip()[:90]}")
        for i, line in enumerate(doc.clean[doc.body_start:], start=doc.body_start):
            if PLACEHOLDER.search(line):
                rep.warn("placeholder", f"{doc.rel}:{i + 1}", "placeholder text (TBD/TODO/???)")
            for m in DREF.finditer(line):
                d = proj.decisions.get(m.group(1))
                if d is None:
                    rep.err("unknown-decision", f"{doc.rel}:{i + 1}", f"{m.group(1)} is not in decisions.md")
                elif d["fields"].get("status") == "superseded":
                    rep.err("stale-decision", f"{doc.rel}:{i + 1}", f"{m.group(1)} is superseded; cite its replacement")

    # --- links (all docs) --------------------------------------------------
    for doc in proj.all_docs():
        for i, line in enumerate(doc.clean):
            for m in LINK.finditer(line):
                target = m.group(2)
                if re.match(r"^[A-Za-z][A-Za-z0-9+.\-]*:", target):
                    continue
                path_part, _, frag = target.partition("#")
                tpath = doc.path if not path_part else (doc.path.parent / path_part)
                if not tpath.exists():
                    rep.err("broken-link", f"{doc.rel}:{i + 1}", f"'{path_part}' does not exist")
                elif frag and tpath.suffix == ".md" and frag not in proj.anchors_of(tpath):
                    rep.err("broken-anchor", f"{doc.rel}:{i + 1}", f"'{tpath.name}' has no section '#{frag}'")

    # --- decisions ---------------------------------------------------------
    titles = {}
    for did, d in proj.decisions.items():
        f, where = d["fields"], f"decisions.md:{d['line']} {did}"
        for k in ("status", "owner", "date", "decision"):
            if not f.get(k):
                rep.err("decision-field", where, f"missing '{k}'")
        status = f.get("status")
        if status and status not in DECISION_STATUSES:
            rep.err("decision-field", where, f"status '{status}' not one of {DECISION_STATUSES}")
        if f.get("date") and not re.match(r"^\d{4}-\d{2}-\d{2}$", f["date"]):
            rep.warn("decision-field", where, "date should be YYYY-MM-DD")
        if f.get("owner"):
            mod, slug, e = proj.resolve(f["owner"])
            if e:
                rep.err("decision-owner", where, e)
            elif status == "active":
                text = "\n".join(proj.modules[mod].subtree(slug))
                if f"[{did}]" not in text:
                    rep.err("owner-missing-citation", where,
                            f"owner '{f['owner']}' never cites [{did}]; the owner section must state this decision")
        for sid in re.findall(r"D-\d+", f.get("supersedes", "")):
            other = proj.decisions.get(sid)
            if other is None:
                rep.err("supersede-chain", where, f"supersedes unknown {sid}")
            else:
                if other["fields"].get("status") != "superseded":
                    rep.err("supersede-chain", where, f"supersedes {sid}, but {sid} is not marked superseded")
        by = f.get("superseded_by", "")
        if status == "superseded":
            replaced = by or any(did in re.findall(r"D-\d+", o["fields"].get("supersedes", ""))
                                 for o in proj.decisions.values())
            if not replaced:
                rep.err("supersede-chain", where, "superseded but nothing replaces it (add 'superseded_by')")
            for bid in re.findall(r"D-\d+", by):
                b = proj.decisions.get(bid)
                if b is None:
                    rep.err("supersede-chain", where, f"superseded_by unknown {bid}")
                elif did not in b["fields"].get("supersedes", ""):
                    rep.warn("supersede-chain", where, f"{bid} does not list {did} under 'supersedes'")
        if status == "active":
            key = re.sub(r"\W+", " ", d["title"].lower()).strip()
            if key and key in titles:
                rep.warn("duplicate-decision", where, f"same title as active {titles[key]}")
            titles.setdefault(key, did)

    # --- tasks -------------------------------------------------------------
    for fname, tasks in proj.tasks.items():
        ids = set()
        for t in tasks:
            where = f"tasks/{fname}.md:{t['line']} {t['id']}"
            if t["id"] in ids:
                rep.err("task-id", where, "duplicate task id in this file")
            ids.add(t["id"])
            if not t["implements"]:
                rep.err("task-no-link", where, "no 'implements: module#section' line")
            for ref in t["implements"]:
                _, _, e = proj.resolve(ref)
                if e:
                    rep.err("task-bad-ref", where, f"implements '{ref}': {e}")
            if t["review"] and not t["done"]:
                rep.warn("task-needs-review", where, f"flagged for review: {t['review']}")

    # --- coverage and status consistency ----------------------------------
    refs = proj.active_task_refs()
    covered = {}
    for fname, t, mod, slug in refs:
        covered.setdefault(mod, set()).add(slug)
    for name, doc in proj.modules.items():
        status = doc.meta.get("status")
        mod_tasks = [(f, t) for f, t, m, _ in refs if m == name]
        if status != "implemented":
            slugs = covered.get(name, set())
            for i, s in enumerate(doc.secs):
                if s["level"] != 2 or s["slug"] in META_SLUGS:
                    continue
                if any(NO_TASK in ln for ln in doc.lines[s["line"]:s["line"] + 3]):
                    continue
                if None in slugs or (doc.subtree_slugs(s["slug"]) & slugs):
                    continue
                rep.warn("uncovered-section", f"{doc.rel}:{s['line'] + 1}",
                         f"section '{s['title']}' has no task implementing it")
        open_tasks = [t for _, t in mod_tasks if not t["done"]]
        if status == "implemented" and open_tasks:
            rep.err("status-mismatch", doc.rel, f"marked implemented but {len(open_tasks)} task(s) still open")
        if status == "planned" and mod_tasks and not open_tasks:
            rep.warn("status-mismatch", doc.rel, "all tasks done but status is still 'planned'")
        if status == "in-progress" and not mod_tasks:
            rep.warn("status-mismatch", doc.rel, "in-progress but no active tasks point at it")
    return rep


def cmd_check(proj, strict):
    rep = run_checks(proj)
    rep.print()
    e, w = rep.count("ERROR"), rep.count("WARN")
    print(f"\n{len(proj.modules)} modules, {len(proj.decisions)} decisions, "
          f"{sum(len(t) for t in proj.tasks.values())} active tasks: {e} error(s), {w} warning(s)")
    return 1 if e or (strict and w) else 0


