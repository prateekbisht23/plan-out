def main(argv=None):
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--docs", default="docs", help="docs directory (default: ./docs)")
    common.add_argument("--strict", action="store_true", help="treat warnings as errors")
    ap = argparse.ArgumentParser(prog="check.py", description=__doc__.split("\n")[0], parents=[common])
    sub = ap.add_subparsers(dest="cmd")
    sub.add_parser("check", parents=[common])
    p = sub.add_parser("impact", parents=[common]); p.add_argument("ref")
    p = sub.add_parser("archive", parents=[common]); p.add_argument("feature")
    p.add_argument("--date", default=datetime.date.today().isoformat())
    p = sub.add_parser("index", parents=[common]); p.add_argument("--force", action="store_true")
    p = sub.add_parser("ledger", parents=[common]); p.add_argument("ledger_json")
    a = ap.parse_args(argv)
    if not Path(a.docs).is_dir():
        print(f"ERROR: docs directory '{a.docs}' not found")
        return 2
    proj = Project(a.docs)
    cmd = a.cmd or "check"
    if cmd == "check":
        return cmd_check(proj, a.strict)
    if cmd == "impact":
        return cmd_impact(proj, a.ref)
    if cmd == "archive":
        return cmd_archive(proj, a.feature, a.date, a.strict)
    if cmd == "index":
        return cmd_index(proj, a.force)
    return cmd_ledger(proj, a.ledger_json, a.strict)


if __name__ == "__main__":
    sys.exit(main())
