def cmd_impact(proj, ref):
    mod, slug, e = proj.resolve(ref)
    if e:
        print(f"ERROR: {e}")
        return 1
    doc = proj.modules[mod]
    slugs = doc.subtree_slugs(slug)
    label = f"{mod}#{slug}" if slug else mod
    print(f"Impact of changing {label}\n")

    owned = []
    for did, d in proj.decisions.items():
        m2, s2, err = proj.resolve(d["fields"].get("owner", ""))
        if not err and m2 == mod and (slug is None or s2 in slugs):
            owned.append(did)
    print("Decisions owned here (supersede, do not overwrite):")
    for did in owned:
        f = proj.decisions[did]["fields"]
        print(f"  {did} [{f.get('status')}] {proj.decisions[did]['title']}")
    if not owned:
        print("  (none; if you are changing a fact, check it has an owner)")

    print("\nTasks implementing this (active):")
    hits = [(f, t) for f, t, m, s in proj.active_task_refs()
            if m == mod and (slug is None or s is None or s in slugs)]
    for f, t in hits:
        print(f"  tasks/{f}.md {t['id']} [{'x' if t['done'] else ' '}] {t['title']}")
    if not hits:
        print("  (none)")

    print("\nOther places that link to or cite it (review these):")
    found = False
    for name, other in proj.modules.items():
        for i, line in enumerate(other.clean):
            for m in LINK.finditer(line):
                path_part, _, frag = m.group(2).partition("#")
                if Path(path_part).stem == mod and name != mod and (not frag or slug is None or frag in slugs):
                    print(f"  {other.rel}:{i + 1} links to {m.group(2)}")
                    found = True
            if name != mod:
                for dm in DREF.finditer(line):
                    if dm.group(1) in owned:
                        print(f"  {other.rel}:{i + 1} cites {dm.group(1)}")
                        found = True
    if not found:
        print("  (none)")
    return 0


